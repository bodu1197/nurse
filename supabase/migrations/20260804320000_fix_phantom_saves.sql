-- 🔴 "오늘 이력서를 저장했다" 고 찍혀 있는데 **한 번도 로그인한 적이 없는 사람**이 3명 있다.
--
-- 정나영·김사랑·김도이 — 셋 다 last_edited_at 이 2026-08-04 12:42:16 으로 **초까지 같고**,
-- auth.users.last_sign_in_at 은 null 이다. 로그인한 적이 없으면 저장했을 수가 없다.
--
-- 원인은 20260804290000 의 백필 규칙이다: "같은 초에 **4건 이상**이면 배치로 본다".
-- 12:42:16 에는 정확히 **3건**이 몰렸다. 3은 4보다 작아서 사람이 저장한 것으로 통과했다.
-- 임계값을 숫자 하나로 잡은 것이 잘못이었다 — 배치는 3건짜리도 있다.
--
-- 로그인 기록이 없는 행은 사람이 저장한 것이 아니다. 그것이 확실한 판정 기준이다.
-- (반대 방향의 오차 — 배치가 사람의 저장 시각을 먼저 덮어써서 아예 안 잡히는 경우 — 는
--  20260804310000 에서 로그인 시각을 하한으로 써서 복구했다.)

update public.resumes r
   set last_edited_at = r.created_at
  from auth.users u
 where u.id = r.profile_id
   and u.last_sign_in_at is null
   and r.last_edited_at > r.created_at;
