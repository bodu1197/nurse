-- 게시판 글의 사진. 구 널스넷 글 44건(사진게시판·간호뉴스·이벤트 등)이 본문에 이미지를 갖고 있었다.
-- 본문은 평문으로 옮기므로(HTML 을 그대로 렌더하면 XSS 다) 이미지는 따로 담아 본문 아래에 붙인다.
--
-- 값의 두 형태:
--   · "2024/10/18/a08308….jpeg" — 우리 board 버킷의 오브젝트 경로(구 널스넷에서 옮겨온 파일)
--   · "https://…"              — 뉴스 기사 이미지처럼 남의 서버에 있는 것. 받아오지 않고 주소만 둔다
--                                (남의 저작물을 우리 저장소로 복사할 이유가 없다).
alter table public.board_posts add column if not exists images text[] not null default '{}';

comment on column public.board_posts.images is
  '본문에 딸린 사진. board 버킷의 오브젝트 경로 또는 외부 URL(https://…). 화면은 본문 아래에 순서대로 붙인다.';

-- 회원이 쓰기로 건드릴 수 없게 둔다 — 이 테이블은 컬럼 단위로만 쓰기를 허용한다(20260724160000).
-- 새 컬럼에는 GRANT 를 주지 않으므로 지금 상태로 이미 잠겨 있다. 게시판에 사진 첨부 기능이 생기면
-- 그때 grant insert (images) 를 열면 된다.

-- board 버킷은 **공개**다(스크립트가 만든다). 인재 사진(avatars)과 다른 판단인 이유:
--   · 얼굴 사진이 아니라 공지 포스터·행사 안내·뉴스 이미지이고, 구 널스넷에서 이미 누구나 볼 수 있었다.
--   · 경로가 라이믹스가 붙인 32자리 해시라 주소를 조합해 훑을 수 없다.
--   · 비공개로 두면 서명 URL 이 필요한데, 수명이 짧아 화면을 열어둔 채 스크롤하면 사진이 깨진다
--     (인재 사진에서 겪은 문제 그대로다).
