export type AdPlanPrice = {
  /** 노출 일수 */
  days: number;
  /** 정가(VAT 포함) */
  list: number;
  /** 판매가(VAT 포함) */
  sale: number;
};

export type AdPlan = {
  key: string;
  name: string;
  /** 등급 강조 — VVIP·VIP 는 레거시에서 '프리미엄', 나머지는 '위치별'로 묶여 있었다 */
  group: "프리미엄 상품안내" | "위치별 상품안내";
  /** PC 광고 위치 */
  pc: readonly string[];
  /** 모바일 광고 위치 */
  mobile: readonly string[];
  /** 인재 서칭 열람 건수 — 결제일 기준 1일 n건, 이후 일 m건 */
  search: { firstDay: number; perDay: number };
  prices: readonly AdPlanPrice[];
};

/**
 * 할인율은 **행마다 정가·판매가에서 계산한다**. 상수 40 을 모든 행에 찍으면 안 된다 —
 * 베스트 60일만 169,000 → 104,400(38%)이라, 40% 배지 옆에 그 숫자가 놓이면 화면이
 * 스스로를 반증한다(손님이 40%를 근거로 101,400원을 요구할 근거가 우리 화면에 있다).
 */
export const discountPct = (list: number, sale: number) => Math.round((1 - sale / list) * 100);

